#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn fallback_covers_every_known_hero() {
        assert!(HEROES.len() >= 120);
        let mut ids = HashSet::new();
        for hero in HEROES {
            assert!(ids.insert(hero.id), "duplicate hero id {}", hero.id);
            assert!(!hero.name.is_empty());
            assert!(!hero.localized_name.is_empty());
            assert!(!hero.icon.is_empty());
            assert!(hero.name.starts_with("npc_dota_hero_"));
        }
        assert!(
            HEROES
                .iter()
                .any(|hero| hero.id == 1 && hero.localized_name == "Anti-Mage")
        );
    }
}
